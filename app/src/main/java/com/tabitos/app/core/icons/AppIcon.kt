/** Index tables persisted by lists and habits: the original options first, then the rest of the catalog. */
object AppIconTables {
    val list: List<AppIcon> = withLegacyFirst(
        AppIcon.LIST, AppIcon.WORK, AppIcon.HOME, AppIcon.STUDY, AppIcon.HEART, AppIcon.STAR,
    )
    val habit: List<AppIcon> = withLegacyFirst(
        AppIcon.LEAF, AppIcon.STUDY, AppIcon.HOME, AppIcon.WORK, AppIcon.HEART, AppIcon.STAR, AppIcon.BLOCK,
        AppIcon.DRINK, AppIcon.CIGARETTE, AppIcon.ADULT_CONTENT, AppIcon.SCREEN_TIME, AppIcon.FAST_FOOD,
        AppIcon.SWEETS, AppIcon.BETTING, AppIcon.GAME, AppIcon.GROCERIES, AppIcon.SLEEP,
    )

    private fun withLegacyFirst(vararg legacy: AppIcon): List<AppIcon> =
        legacy.toList() + AppIcon.entries.filterNot { it in legacy }
}
